// Offline Node built-in assertions. No npm, DOM, network or build pipeline.
const assert = require('node:assert/strict');
const view = require('../webapp/static/dashboard.js');
assert.equal(view.number(null), '—');
assert.equal(view.number(NaN), '—');
assert.equal(view.number(1234.5), '1,234.50');
assert.equal(view.percent(1.5), '+1.50%');
assert.equal(view.percent(-1.5), '-1.50%');
assert.equal(view.priceTone(-1), 'down');
assert.equal(view.priceTone(1), 'up');
assert.equal(view.quality('stale').tone, 'orange');
assert.equal(view.quality('unavailable').label, '获取失败');
assert.equal(view.quality('future-new-state').label, '待获取');
assert.equal(view.escapeText('<img src=x onerror="x">'), '&lt;img src=x onerror=&quot;x&quot;&gt;');
assert.equal(view.trendTone('偏强'),'red');
assert.equal(view.trendTone('偏弱'),'green');
assert.equal(view.timestamp('bad',true),'—');
assert.equal(view.timestamp('2026-10-19T06:50:00Z',true),'14:50:00');
const specs = [{code:'A'},{code:'B'},{code:'C'}];
const items = new Map([['A',{trend:'偏强',change_pct:2}],['B',{trend:'偏弱',change_pct:-1}]]);
assert.deepEqual(view.ordered(items,'all','desc',specs).map(r=>r.code),['A','B','C']);
assert.deepEqual(view.ordered(items,'all','asc',specs).map(r=>r.code),['B','A','C']);
assert.deepEqual(view.ordered(items,'偏强','default',specs).map(r=>r.code),['A']);
assert.deepEqual(view.ordered(items,'数据不足','default',specs).map(r=>r.code),['C']);
assert.equal(items.get('A').change_pct,2);
const rawError = 'ProxyError: RemoteDisconnected https://example.invalid/api?very_long_query=123';
assert.match(view.errorPresentation(rawError).summary, /连接中断/);
assert.doesNotMatch(view.errorPresentation(rawError).summary, /https|very_long_query/);
assert.equal(view.errorPresentation(rawError).detail, rawError);
assert.match(view.errorPresentation('ReadTimeout timeout').summary, /超时/);
assert.match(view.errorPresentation('IndexDataError OHLC冲突').summary, /校验/);
assert.equal(view.errorPresentation(null).detail, '');
assert.doesNotMatch(view.errorPresentation('ProxyError http://user:secret@proxy.invalid').detail, /user:secret/);
assert.match(view.sourcePresentation('sohu/index-daily').label, /搜狐/);
assert.match(view.sourcePresentation('eastmoney/index-daily').label, /东方财富/);
assert.match(view.sourcePresentation('tencent/index-daily').label, /腾讯/);
console.log('Dashboard presentation: 30 assertions passed (offline).');
